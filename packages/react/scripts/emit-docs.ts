import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { a11yMeta } from "../src/a11y-meta.js";
import { boundFamilies, themingSection } from "./docs-sections.js";

interface Prop {
  name: string;
  type: string;
  required: boolean;
  default: string | number | null;
  description: string;
}

interface Component {
  name: string;
  description: string;
  props: Prop[];
}

interface Guidance {
  variants: Array<{ variant: string; intent: string; typicalUse: string }>;
  rules: string[];
  states: Record<string, string>;
}

const root = fileURLToPath(new URL("..", import.meta.url));

// Read manifest and guidance
let components: Component[];
let guidance: Guidance;

try {
  components = JSON.parse(readFileSync(join(root, "dist/manifest.json"), "utf8")).components;
} catch {
  console.error("[react] ERROR: dist/manifest.json not found. Run `pnpm --filter @handamade/psi-tokens build` and `pnpm --filter @handamade/psi-react build` first.");
  process.exit(1);
}

try {
  guidance = JSON.parse(readFileSync(join(root, "../tokens/dist/guidance.json"), "utf8"));
} catch {
  console.error("[react] ERROR: ../tokens/dist/guidance.json not found. Run `pnpm --filter @handamade/psi-tokens build` first.");
  process.exit(1);
}

// Escape and sanitize markdown table cells (collapse newlines and escape pipes)
function escapeCell(text: string | number | null): string {
  return String(text ?? "—")
    .replace(/\s*\n\s*/g, " ")
    .replace(/\|/g, "\\|");
}

// Convert camelCase to kebab-case
function toKebabCase(str: string): string {
  return str.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

mkdirSync(join(root, "docs"), { recursive: true });

// D128: every component token family's generated declarations, and every
// component's source file, so a member without a family of its own can say
// which family its stylesheet binds.
const familyDir = join(root, "../tokens/dist/components");
const familyVars: Record<string, string> = Object.fromEntries(
  readdirSync(familyDir)
    .filter((f) => f.endsWith(".vars.css"))
    .map((f) => [f.slice(0, -".vars.css".length), readFileSync(join(familyDir, f), "utf8")]),
);
const sourceFiles = new Map<string, string>();
for (const entry of readdirSync(join(root, "src"), { recursive: true, withFileTypes: true })) {
  if (!entry.isFile() || !/^[A-Z][A-Za-z0-9]*\.tsx$/.test(entry.name)) continue;
  sourceFiles.set(basename(entry.name, ".tsx"), join(entry.parentPath, entry.name));
}

/** The CSS of the modules a component's source file imports. */
function importedCss(name: string): string {
  const file = sourceFiles.get(name);
  if (!file) return "";
  const source = readFileSync(file, "utf8");
  return [...source.matchAll(/from\s+"(\.[^"]+\.module\.css)"/g)]
    .map((m) => readFileSync(join(dirname(file), m[1]), "utf8"))
    .join("\n");
}

for (const c of components) {
  // Build props table
  const props = c.props
    .map(
      (p) =>
        `| \`${escapeCell(p.name)}\` | \`${escapeCell(p.type)}\` | ${escapeCell(p.default)} | ${p.required ? "yes" : "no"} | ${escapeCell(p.description)} |`
    )
    .join("\n");

  // Determine token name (special cases where the component's PascalCase
  // name doesn't kebab-case to its actual --psi-{component}-* token prefix)
  const TOKEN_NAME_OVERRIDES: Record<string, string> = {
    IconButton: "button",
    FieldStack: "field",
    NavBar: "navbar",
    NavGroup: "nav-tree",
    NavItem: "nav-tree",
    SegmentedControl: "segmented",
    Segment: "segmented",
  };
  const familyName = TOKEN_NAME_OVERRIDES[c.name] ?? toKebabCase(c.name);
  const tokenName = `--psi-${familyName}-*`;

  // HAN-41: only claim token overrides / derived states the family really has.
  let varsCss: string | null;
  try {
    varsCss = readFileSync(join(root, `../tokens/dist/components/${familyName}.vars.css`), "utf8");
  } catch {
    varsCss = null;
  }

  // Check if component has variant prop
  const hasVariant = c.props.some((p) => p.name === "variant");

  // Build variant guidance section (only if component has variant prop)
  const variantGuidanceSection = hasVariant
    ? `## Variant guidance

${guidance.variants.map((v) => `- **${v.variant}** — ${v.intent}. ${v.typicalUse}.`).join("\n")}`
    : "";

  // Build rules section
  const rulesSection = `## Rules

${guidance.rules.map((r: string) => `- ${r}`).join("\n")}`;

  // Build keyboard & assistive tech section (only if the component has an a11y-meta entry)
  const a11y = a11yMeta[c.name];
  const a11ySection = a11y
    ? `## Keyboard & assistive tech

| Keys | Behavior |
|---|---|
${a11y.keyboard.map((k) => `| ${escapeCell(k.keys)} | ${escapeCell(k.behavior)} |`).join("\n")}
${a11y.notes ? `\n${a11y.notes}` : ""}

`
    : "";

  const md = `<!-- Generated by emit-docs.ts — do not edit. -->
# ${c.name}

${c.description}

## Props

| Prop | Type | Default | Required | Description |
|---|---|---|---|---|
${props}

${a11ySection}## Theming

${themingSection(
  tokenName,
  varsCss,
  guidance.states as { hover: string; active: string },
  varsCss === null ? boundFamilies(importedCss(c.name), familyVars) : [],
)}

${variantGuidanceSection}

${rulesSection}
`;

  writeFileSync(join(root, "docs", `${c.name}.md`), md);
}

console.log(`[react] wrote docs/*.md (${components.length})`);
